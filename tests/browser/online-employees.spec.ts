import { test, expect, mockService, login } from './fixtures.js';

for (const role of ['employee', 'admin', 'manager', 'viewer'] as const) for (const width of [390, 1280]) test(`online employee dropdown stays above platform for ${role} at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  const service = await mockService(page, { role });
  const people = Array.from({ length: 25 }, (_, i) => ({ ...service.account, id: `online-${i}`, name: `موظفة حاضرة ${i}`, role: 'employee' }));
  await page.route('**/rpc/get_read_model', route => route.fulfill({ json: { generatedAt: '2026-11-04T12:00:00+03:00', directory: [service.account, ...people], reviews: [], notes: [], hours: {}, disabledEmployeeIds: [] } }));
  people[1] = { ...people[1], role: 'admin' };
  people[2] = { ...people[2], role: 'manager', branch: 'شرق' };
  people[3] = { ...people[3], role: 'manager', branch: 'سلام' };
  people[0] = { ...people[0], role: 'viewer', name: 'محمد' };
  let failed = false;
  await page.route('**/rpc/get_online_employees', route => failed ? route.fulfill({ status: 503, json: { message: 'unavailable' } }) : route.fulfill({ json: Object.fromEntries(people.map(person => [person.id, person.id === 'online-24' ? '2026-11-04T11:50:00+03:00' : '2026-11-04T12:05:00+03:00'])) }));
  await login(page, { destination: 'leaderboard' });
  const toggle = page.getByRole('button', { name: 'الموظفات المتصلات', exact: true });
  await expect(toggle.locator('[data-online]')).toHaveAttribute('data-online', 'true');
  const panel = page.getByRole('region', { name: 'آخر المتصلات' });
  await expect(panel.locator('li')).toHaveCount(5);
  await expect(panel.locator('li').first()).toHaveText('محمد الحبيب');
  await expect(panel.locator('li').nth(2)).toHaveCSS('opacity', '1');
  await expect(panel.locator('li').nth(3)).toHaveCSS('opacity', '0.55');
  await expect(panel.locator('li').nth(4)).toHaveCSS('opacity', '0.23');
  await toggle.click();
  await expect(panel.locator('li')).toHaveCount(24);
  await expect(panel).toContainText('إدارة شرق');
  await expect(panel).toContainText('إدارة سلام');
  await expect(panel.getByText(people[1].name, { exact: true })).toHaveCount(0);
  await expect(panel.getByText(people[2].name, { exact: true })).toHaveCount(0);
  await expect(panel.locator('li').last().getByRole('img')).toHaveCount(0);
  await expect(panel).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
  const buttonBox = (await toggle.boundingBox())!, header = (await page.locator('.recognition-header').boundingBox())!;
  expect(buttonBox.y).toBeGreaterThanOrEqual(header.y + header.height);
  const box = (await panel.boundingBox())!, platform = (await page.locator('.crystal-platform').boundingBox())!;
  expect(box.y + box.height).toBeLessThanOrEqual(platform.y);
  expect(box.x).toBeGreaterThanOrEqual(0);
  expect(box.x + box.width).toBeLessThanOrEqual(width);
  await page.screenshot({ path: test.info().outputPath('online-employees.png') });
  await page.keyboard.press('Escape');
  await expect(panel.locator('li')).toHaveCount(5);
  await expect(toggle).toBeFocused();
  await page.clock.setFixedTime(new Date('2026-11-04T12:06:00+03:00'));
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await expect(toggle.locator('[data-online]')).toHaveAttribute('data-online', 'false');
  failed = true;
  await page.reload();
  await toggle.click();
  await expect(panel).toContainText('تعذر التحميل');
  expect(service.unexpected).toEqual([]);
});
